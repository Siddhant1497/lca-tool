import React, { Suspense, useState } from 'react';
import type { SharePayload } from '../utils/share';
import { HubProvider } from '../context/HubContext';
import { LCAProvider } from '../context/LCAContext';
import { ShareProvider } from '../context/ShareContext';
import { ToastProvider } from '../components/ui/Toast';
import { useUi } from '../context/UiContext';
import Icon from '../components/ui/Icon';
import CommandCenter from '../components/pages/CommandCenter';
import Strategy from '../components/pages/Strategy';
import Disclosures from '../components/pages/Disclosures';

type Tab = 'overview' | 'strategy' | 'disclosures';

/** Read-only dashboard a consultant sends to a client. Shows only the sections chosen when it was created. */
const ViewerApp: React.FC<{ payload: SharePayload }> = ({ payload }) => {
  const { config, client, state } = payload;
  const { theme, toggleTheme } = useUi();
  const has = (k: string) => config.sections.includes(k as never);
  const tabs: { id: Tab; label: string; icon: 'grid' | 'target' | 'clipboard' }[] = [
    ...(['kpis', 'pathway', 'split', 'inventory', 'scope3', 'intensity', 'levers', 'certs'].some(has) ? [{ id: 'overview' as Tab, label: 'Overview', icon: 'grid' as const }] : []),
    ...(has('strategy') ? [{ id: 'strategy' as Tab, label: 'Decarbonisation strategy', icon: 'target' as const }] : []),
    ...(has('disclosures') && config.frameworks.length ? [{ id: 'disclosures' as Tab, label: 'Disclosures', icon: 'clipboard' as const }] : []),
  ];
  const [tab, setTab] = useState<Tab>(tabs[0]?.id ?? 'overview');
  const date = new Date(config.createdAt).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });

  return (
    <HubProvider fixed={{ state, clientName: client }}>
      <LCAProvider>
        <ShareProvider config={config}>
          <ToastProvider>
            <div className="viewer">
              <header className="v-head">
                <div className="v-brand">
                  <span className="brand-mark"><Icon name="leaf" size={18} /></span>
                  <div><div className="v-client">{client}</div><div className="v-title">{config.title}</div></div>
                </div>
                <div className="row" style={{ marginLeft: 'auto', gap: 10 }}>
                  <span className="cell-sub v-meta">Prepared by <b>{config.preparedBy || 'your consultant'}</b> · {date}</span>
                  <button className="icon-btn" onClick={toggleTheme} aria-label="Toggle theme"><Icon name={theme === 'dark' ? 'sun' : 'moon'} /></button>
                </div>
              </header>
              {tabs.length > 1 && (
                <nav className="v-tabs" role="tablist">
                  {tabs.map((t) => (
                    <button key={t.id} role="tab" aria-selected={tab === t.id} className={`tab${tab === t.id ? ' active' : ''}`} onClick={() => { setTab(t.id); window.scrollTo({ top: 0 }); }}>
                      <Icon name={t.icon} size={15} />{t.label}
                    </button>))}
                </nav>
              )}
              <main className="v-main">
                {config.note && <div className="notice info"><Icon name="info" size={16} /><span className="grow" style={{ whiteSpace: 'pre-wrap' }}>{config.note}</span></div>}
                {tabs.length === 0 && <div className="card"><p>No sections were included in this view.</p></div>}
                <Suspense fallback={null}>
                  {tab === 'overview' && <CommandCenter />}
                  {tab === 'strategy' && <Strategy />}
                  {tab === 'disclosures' && <Disclosures />}
                </Suspense>
                <footer className="v-foot">Read-only view generated by SustainHub on {date}. Figures reflect the data available on that date{state.isSample ? ' — SAMPLE DATA, NOT REAL' : ''}.</footer>
              </main>
            </div>
          </ToastProvider>
        </ShareProvider>
      </LCAProvider>
    </HubProvider>
  );
};
export default ViewerApp;
